export type IconName = keyof typeof ICONS;

/** L'icône de chaque genre d'action (pour les bulles et les listes). */
export const ACT_ICON: Record<ActKind, IconName> = {
  search: 'search', web: 'web', read: 'read', write: 'write', edit: 'write', bash: 'bash', plan: 'plan', skill: 'star', mcp: 'plug', other: 'gear',
};

// les rectangles de chaque icône, calculés une fois (une rangée de pixels voisins = un seul rectangle)
const RUNS = new Map<IconName, [number, number, number][]>();
function runs(name: IconName) {
  let r = RUNS.get(name);
  if (r) return r;
  r = [];
  ICONS[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      const start = x;
      while (x < row.length && row[x] === '#') x++;
      r!.push([start, y, x - start]);
    }
  });
  RUNS.set(name, r);
  return r;
}

export function PixelIcon({ name, size = 14, title, className }: { name: IconName; size?: number; title?: string; className?: string }) {
  return (
    <svg
      className={`picon ${className ?? ''}`}
      width={size}
      height={size}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
    >
      {title && <title>{title}</title>}
      {runs(name).map(([x, y, w]) => <rect key={`${x}-${y}`} x={x} y={y} width={w} height={1} fill="currentColor" />)}
    </svg>
  );
}
